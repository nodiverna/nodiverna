-- Written by hand below this line: the cleanup triggers. scope_id of
-- os_esu_overrides is polymorphic, so no foreign key removes the ESU date of a
-- removed device or a deleted group; the software tables keep no rows of a
-- removed device (revoked=1). Like alert_rule_overrides_removed_device in
-- 0001_alert_rule_overrides.sql. They raise nothing.
CREATE FUNCTION health_signals_removed_device() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 DELETE FROM os_esu_overrides WHERE scope_type='device' AND scope_id=NEW.id;
 DELETE FROM device_software WHERE server_id=NEW.id;
 DELETE FROM device_software_changes WHERE server_id=NEW.id;
 DELETE FROM device_software_state WHERE server_id=NEW.id;
 RETURN NULL;
END $$;
CREATE TRIGGER health_signals_removed_device AFTER UPDATE OF revoked ON servers FOR EACH ROW WHEN (NEW.revoked=1) EXECUTE FUNCTION health_signals_removed_device();

CREATE FUNCTION os_esu_overrides_removed_group() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 DELETE FROM os_esu_overrides WHERE scope_type='group' AND scope_id=OLD.id;
 RETURN NULL;
END $$;
CREATE TRIGGER os_esu_overrides_removed_group AFTER DELETE ON device_groups FOR EACH ROW EXECUTE FUNCTION os_esu_overrides_removed_group();
