CREATE FUNCTION device_groups_update_paths() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 DELETE FROM device_group_paths
  WHERE group_id IN (SELECT group_id FROM device_group_paths WHERE ancestor_id=NEW.id)
   AND ancestor_id IN (SELECT ancestor_id FROM device_group_paths WHERE group_id=NEW.id AND depth>0);
 INSERT INTO device_group_paths(group_id,ancestor_id,depth)
  SELECT subtree.group_id,ancestor.ancestor_id,subtree.depth+ancestor.depth+1
  FROM device_group_paths subtree JOIN device_group_paths ancestor ON ancestor.group_id=NEW.parent_id
  WHERE subtree.ancestor_id=NEW.id;
 RETURN NULL;
END $$;
