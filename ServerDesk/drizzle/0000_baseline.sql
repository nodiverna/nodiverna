CREATE FUNCTION audit_insert_customer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM customers WHERE id=NEW.customer_id) THEN RAISE EXCEPTION 'customer-missing'; END IF;
 IF NEW.server_id IS NOT NULL AND EXISTS(SELECT 1 FROM servers WHERE id=NEW.server_id AND customer_id IS DISTINCT FROM NEW.customer_id) THEN RAISE EXCEPTION 'customer-mismatch'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER audit_insert_customer BEFORE INSERT ON audit FOR EACH ROW WHEN (NEW.customer_id IS NOT NULL) EXECUTE FUNCTION audit_insert_customer();

