 IF EXISTS(SELECT 1 FROM customers WHERE id=NEW.customer_id AND status='disabled') THEN RAISE EXCEPTION 'customer-disabled'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER servers_insert_customer_disabled BEFORE INSERT ON servers FOR EACH ROW EXECUTE FUNCTION servers_insert_customer_disabled();

CREATE FUNCTION servers_update_customer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM customers WHERE id=NEW.customer_id) THEN RAISE EXCEPTION 'customer-missing'; END IF;
 IF EXISTS(SELECT 1 FROM device_group_members member JOIN device_groups grp ON grp.id=member.group_id WHERE member.server_id=NEW.id AND grp.customer_id<>NEW.customer_id) THEN RAISE EXCEPTION 'customer-mismatch'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER servers_update_customer BEFORE UPDATE OF customer_id ON servers FOR EACH ROW EXECUTE FUNCTION servers_update_customer();

CREATE FUNCTION servers_update_customer_catalog() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM role_assignments moved_assignment JOIN rbac_roles moved_role ON moved_role.id=moved_assignment.role_id WHERE moved_assignment.scope_type='device' AND moved_assignment.scope_id=OLD.id AND moved_role.customer_id IS NOT NULL AND moved_role.customer_id IS DISTINCT FROM NEW.customer_id)
  OR EXISTS(SELECT 1 FROM automation_scope_assignments moved_scope JOIN automation_templates moved_template ON moved_template.id=moved_scope.template_id WHERE moved_scope.scope_type='device' AND moved_scope.scope_id=OLD.id AND moved_template.customer_id IS NOT NULL AND moved_template.customer_id IS DISTINCT FROM NEW.customer_id) THEN
  RAISE EXCEPTION 'customer-mismatch';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER servers_update_customer_catalog BEFORE UPDATE OF customer_id ON servers FOR EACH ROW WHEN (NEW.customer_id IS DISTINCT FROM OLD.customer_id) EXECUTE FUNCTION servers_update_customer_catalog();

