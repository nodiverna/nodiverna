// The PostgreSQL data layer (runSteps guards roll back audit rows, SERIALIZABLE retries across two pools) and the
// object storage (runtime/storage.mjs): replacements, key checks and no symlink outside the bucket (pnpm test:selfhost).
import assert from 'node:assert/strict';
import {mkdtemp, readFile, rm, symlink, writeFile, mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {createDatabase,sql} from '../../runtime/database.mjs';
import {testDatabase} from '../support/postgres.mjs';
import {dbModule} from '../support/source-database.mjs';
const {runSteps} = dbModule();
import {createStorage} from '../../runtime/storage.mjs';

const temporary = await mkdtemp(join(tmpdir(), 'serverdesk-storage-'));
// An empty PostgreSQL test database with the fixture tables of this file.
const database = await testDatabase({template: false});
const bucketRoot = join(temporary, 'objects');
const bucket = createStorage({OBJECT_STORAGE_DRIVER: 'filesystem', OBJECT_STORAGE_PATH: bucketRoot});

try {
  for (const statement of [sql`CREATE TABLE permissions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, enabled bigint NOT NULL)`, sql`CREATE TABLE audit(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text UNIQUE)`]) await database.exec(statement);
  const inserted = await database.one(sql`INSERT INTO permissions(enabled) VALUES (${1}) RETURNING id`);
  assert.deepEqual(inserted, {id: 1}, 'a new id comes from RETURNING, as a number');
  assert.equal(await database.one(sql`SELECT enabled FROM permissions WHERE id=1`).then(row=>row===null?null:row.enabled), 1);
  assert.equal(await database.one(sql`SELECT enabled FROM permissions WHERE id=999`), null);
  assert.deepEqual(await database.query(sql`SELECT id, enabled FROM permissions`), [{id: 1, enabled: 1}]);

  // This pattern protects real authorization writes throughout the application:
  // an unsuccessful guard must not let a following statement insert an audit row
  // (runSteps with afterChange, lib/server/db.ts).
  const steps = list => database.transaction(tx => runSteps(tx, list));
  const denied = await steps([
    sql`UPDATE permissions SET enabled=0 WHERE id=1 AND enabled=99`,
    {afterChange: sql`INSERT INTO audit(note) VALUES('denied')`},
  ]);
  assert.deepEqual(denied.map(result => result.rowCount), [0, 0]);
  assert.equal(await database.one(sql`SELECT count(*) AS n FROM audit`).then(row=>row===null?null:row.n), 0);
  const allowed = await steps([
    sql`UPDATE permissions SET enabled=0 WHERE id=1 AND enabled=1`,
    {afterChange: sql`INSERT INTO audit(note) VALUES('allowed') RETURNING note`},
  ]);
  assert.deepEqual(allowed.map(result => result.rowCount), [1, 1]);
  assert.deepEqual(allowed[1].rows, [{note: 'allowed'}]);

  // A late uniqueness failure rolls back an earlier permission mutation too.
  await assert.rejects(steps([
    sql`UPDATE permissions SET enabled=1 WHERE id=1`,
    sql`INSERT INTO audit(note) VALUES ('allowed')`,
  ]), error => error.code === '23505');
  assert.equal(await database.one(sql`SELECT enabled FROM permissions WHERE id=1`).then(row=>row===null?null:row.enabled), 0);
  assert.equal(await database.one(sql`SELECT count(*) AS n FROM audit`).then(row=>row===null?null:row.n), 1);
  const concurrent = await Promise.all([
    steps([
      sql`UPDATE permissions SET enabled=1 WHERE id=1 AND enabled=0`,
      {afterChange: sql`INSERT INTO audit(note) VALUES('atomic')`},
    ]),
    database.exec(sql`UPDATE permissions SET enabled=0 WHERE id=999`),
  ]);
  assert.equal(concurrent[0][1].rowCount, 1);
  assert.equal(await database.one(sql`SELECT count(*) AS n FROM audit WHERE note='atomic'`).then(row=>row===null?null:row.n), 1);
  // A second pool on the same database behaves like a second process. Its
  // transactions interleave with this pool's; SERIALIZABLE retries settle conflicts.
  const other = createDatabase({url: database.url, password: database.password, max: 4});
  try {
    const writes = (owner, prefix) => Array.from({length: 10}, (_, index) => owner.transaction(tx => runSteps(tx, [
      sql`INSERT INTO audit(note) VALUES (${`${prefix}-${index}`})`,
      {afterChange: sql`INSERT INTO audit(note) VALUES (${`${prefix}-${index}-guard`})`},
    ])));
    await Promise.all([...writes(database, 'first'), ...writes(other, 'second')]);
  } finally { await other.close(); }
  assert.equal(await database.one(sql`SELECT count(*) AS n FROM audit WHERE note LIKE 'first-%' OR note LIKE 'second-%'`).then(row=>row===null?null:row.n), 40);
  const returning = await database.query(sql`INSERT INTO audit(note) VALUES ('single-returning') RETURNING id`);
  assert.equal(returning.length, 1);
  assert.equal(typeof returning[0].id, 'number');

  const bytes = Uint8Array.from([0, 255, 128, 42]);
  const stored = await bucket.put('transfers/example/chunk', bytes, {
    customMetadata: {sha256: 'proof', label: 'Grüße'},
    httpMetadata: {contentType: 'application/octet-stream', cacheControl: 'no-store'},
  });
  assert.equal(stored.size, bytes.length);
  assert.equal(stored.etag, createHash('sha256').update(bytes).digest('hex'));
  const head = await bucket.head('transfers/example/chunk');
  assert.deepEqual(head.customMetadata, {sha256: 'proof', label: 'Grüße'});
  const headers = new Headers();
  head.writeHttpMetadata(headers);
  assert.equal(headers.get('Content-Type'), 'application/octet-stream');
  assert.equal(head.httpEtag, `"${stored.etag}"`);
  const object = await bucket.get('transfers/example/chunk');
  assert.ok(object.body instanceof ReadableStream);
  assert.equal(object.bodyUsed, false);
  assert.deepEqual([...new Uint8Array(await object.arrayBuffer())], [...bytes]);
  assert.equal(object.bodyUsed, true);

  await bucket.put('release/index.json', '{"version":"4.1.0"}');
  assert.deepEqual(await (await bucket.get('release/index.json')).json(), {version: '4.1.0'});
  assert.equal(await (await bucket.get('release/index.json')).text(), '{"version":"4.1.0"}');
  await bucket.put('empty', null);
  assert.equal((await bucket.head('empty')).size, 0);
  assert.equal((await (await bucket.get('empty')).arrayBuffer()).byteLength, 0);
  await bucket.put('streamed', new ReadableStream({start(controller) {controller.enqueue(new TextEncoder().encode('stream'));controller.close();}}));
  assert.equal(await (await bucket.get('streamed')).text(), 'stream');

  // An interrupted replacement leaves the previous, complete object readable.
  await assert.rejects(bucket.put('streamed', new ReadableStream({start(controller) {controller.enqueue(new Uint8Array([1]));controller.error(new Error('interrupted'));}})), /interrupted/);
  assert.equal(await (await bucket.get('streamed')).text(), 'stream');
  await bucket.put('streamed', 'replacement');
  assert.equal(await (await bucket.get('streamed')).text(), 'replacement');

  for (const key of ['cleanup/a', 'cleanup/b', 'cleanup/c', 'unrelated/a']) await bucket.put(key, key);
  const first = await bucket.list({prefix: 'cleanup/', limit: 2});
  assert.deepEqual(first.objects.map(value => value.key), ['cleanup/a', 'cleanup/b']);
  assert.equal(first.truncated, true);
  await bucket.delete(first.objects.map(value => value.key));
  const next = await bucket.list({prefix: 'cleanup/', limit: 2, cursor: first.cursor});
  assert.deepEqual(next.objects.map(value => value.key), ['cleanup/c']);
  assert.equal(next.truncated, false);
  await bucket.delete('cleanup/c');
  assert.equal((await bucket.list({prefix: 'cleanup/'})).objects.length, 0);
  assert.ok(await bucket.head('unrelated/a'));
  await assert.rejects(bucket.list({prefix: 'other/', cursor: first.cursor}), /cursor/);
  await assert.rejects(bucket.list({limit: 0}), /listing/);

  for (const key of ['../outside', '/absolute', 'safe/../../outside', 'safe\\outside', 'D:/outside', 'safe/./part']) {
    await assert.rejects(bucket.put(key, 'unsafe'), /key/);
    await assert.rejects(bucket.get(key), /key/);
    await assert.rejects(bucket.delete(key), /key/);
  }
  await assert.rejects(bucket.delete(['unrelated/a', '../outside']), /key/);
  assert.ok(await bucket.head('unrelated/a'));
  await assert.rejects(bucket.put('unrelated/a', 'unsupported', {onlyIf: {etagDoesNotMatch: '*'}}), /Unsupported/);
  assert.equal(await (await bucket.get('unrelated/a')).text(), 'unrelated/a');
  assert.equal(await bucket.get('missing'), null);
  assert.equal(await bucket.head('missing'), null);
  await bucket.delete('missing');

  // Reject an on-disk symlink instead of reading a target outside the bucket.
  // Windows needs developer mode or symlink privileges; all key checks above
  // always run there, and the actual symlink check also runs in Linux CI.
  // Key 'symlink' lives in namespace '': n/<nh[0:2]>/<nh>/o/<kh>.object.
  const key = 'symlink', hash = createHash('sha256').update(key).digest('hex');
  const namespaceHash = createHash('sha256').update('').digest('hex');
  const directory = join(bucketRoot, 'n', namespaceHash.slice(0, 2), namespaceHash, 'o');
  await mkdir(directory, {recursive: true});
  const outside = join(temporary, 'outside-secret');
  await writeFile(outside, 'must remain untouched');
  try {
    await symlink(outside, join(directory, `${hash}.object`));
    await assert.rejects(bucket.get(key), /Unsafe/);
    await bucket.delete(key);
    assert.equal(await readFile(outside, 'utf8'), 'must remain untouched');
  } catch (error) { if (!['EPERM', 'EACCES'].includes(error.code)) throw error; }

  console.log('Self-host storage: real database atomic authorization/rollback and filesystem object tests passed.');
} finally {
  await database.close();
  // The test creates this unique absolute temporary directory itself.
  assert.ok(temporary.startsWith(join(tmpdir(), 'serverdesk-storage-')));
  await rm(temporary, {recursive: true, force: true, maxRetries: 10, retryDelay: 100});
}
